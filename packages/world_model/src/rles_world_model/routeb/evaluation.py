@dataclass(frozen=True)
class BlockBootstrapDifference:
    """Paired CRPS difference; negative means candidate improves on baseline."""

    horizon: int
    baseline: str
    candidate: str
    mean_difference: float
    ci_95_low: float
    ci_95_high: float
    p_value: float
    block_length: int
    replicates: int


def _crps_per_anchor(samples: np.ndarray, obs: np.ndarray) -> np.ndarray:
    x = np.asarray(samples, dtype=np.float64)
    y = np.asarray(obs, dtype=np.float64)
    if (x.ndim != 2 or y.shape != (x.shape[0],) or x.shape[1] < 2
            or not np.isfinite(x).all() or not np.isfinite(y).all()):
        raise ValueError("finite samples [N,P>=2] and observations [N] required")
    ordered = np.sort(x, axis=1)
    n = x.shape[1]
    first = np.abs(x - y[:, None]).mean(axis=1)
    coeff = 2 * np.arange(n) - n + 1
    correction = (ordered * coeff[None, :]).sum(axis=1) / (n * n)
    return first - correction


def _numeric_sha256(values: np.ndarray, *, dtype: str) -> str:
    canonical = np.ascontiguousarray(values, dtype=np.dtype(dtype))
    digest = hashlib.sha256()
    digest.update(json.dumps({"shape": canonical.shape, "dtype": canonical.dtype.str},
                             separators=(",", ":")).encode("utf-8"))
    digest.update(canonical.tobytes())
    return digest.hexdigest()


def verify_predictive_report_digest(report: Mapping[str, object]) -> bool:
    """Verify the canonical digest generated by the report builder."""
    supplied = report.get("report_sha256")
    if not isinstance(supplied, str) or len(supplied) != 64:
        return False
    payload = {key: value for key, value in report.items() if key != "report_sha256"}
    try:
        canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"), allow_nan=False)
    except (TypeError, ValueError):
        return False
    expected = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    return hmac.compare_digest(supplied, expected)


def _binary_auc(probability: np.ndarray, observed: np.ndarray) -> float | None:
    labels = np.asarray(observed, dtype=bool)
    positives = int(labels.sum())
    negatives = len(labels) - positives
    if not positives or not negatives:
        return None
    order = np.argsort(probability, kind="mergesort")
    sorted_probability = probability[order]
    ranks = np.empty(len(order), dtype=np.float64)
    start = 0
    while start < len(order):
        end = start + 1
        while end < len(order) and sorted_probability[end] == sorted_probability[start]:
            end += 1
        ranks[order[start:end]] = (start + 1 + end) / 2.0
        start = end
    positive_rank_sum = float(ranks[labels].sum())
    return (positive_rank_sum - positives * (positives + 1) / 2.0) / (positives * negatives)


def ensemble_crps(samples: np.ndarray, obs: np.ndarray)->float:
    """Mean empirical CRPS across anchor times; [N,P] samples, [N] observed."""
    return float(np.mean(_crps_per_anchor(samples, obs)))


def diagonal_gaussian_return_nll(
    standardized_mean: np.ndarray,
    standardized_scale: np.ndarray,
    standardized_target: np.ndarray,
    *,
    scaler_mean: np.ndarray,
    scaler_std: np.ndarray,
) -> np.ndarray:
    """Exact per-anchor 1m close-to-close NLL for diagonal Gaussian OHLCV heads.

    RouteB coordinates 0 and 1 are log(open/previous-close) and
    log(close/open). Their sum is the close-to-close log return. Independent
    Gaussian head dimensions therefore induce an exact Gaussian return whose
    mean and variance can be scored without sampling.
    """
    mean = np.asarray(standardized_mean, dtype=np.float64)
    scale = np.asarray(standardized_scale, dtype=np.float64)
    target = np.asarray(standardized_target, dtype=np.float64)
    center = np.asarray(scaler_mean, dtype=np.float64)
    spread = np.asarray(scaler_std, dtype=np.float64)
    if (mean.ndim != 2 or mean.shape[1] != 5 or scale.shape != mean.shape
            or target.shape != mean.shape or center.shape != (5,) or spread.shape != (5,)
            or not all(np.isfinite(value).all() for value in (mean, scale, target, center, spread))
            or np.any(scale <= 0) or np.any(spread <= 0)):
        raise ValueError("finite aligned [N,5] distributions, targets, and scaler are required")
    return_mean = np.sum(mean[:, :2] * spread[:2] + center[:2], axis=1)
    return_variance = np.sum(np.square(scale[:, :2] * spread[:2]), axis=1)
    observed = np.sum(target[:, :2] * spread[:2] + center[:2], axis=1)
    return_std = np.sqrt(return_variance)
    result = 0.5 * np.square((observed - return_mean) / return_std)
    result += np.log(return_std) + 0.5 * np.log(2.0 * np.pi)
    return result


def predictive_horizon_scores(
    path_log_returns: np.ndarray,
    realized_log_returns: np.ndarray,
    *,
    horizons: tuple[int, ...] = (1, 5, 15, 30, 60),
    nll_by_horizon: Mapping[int, np.ndarray] | None = None,
    extreme_threshold: float = -0.02,
    pit_seed: int = 0,
) -> tuple[PredictiveHorizonMetrics, ...]:
    """Score cumulative path distributions on common anchor times.

    NLL is reported only when native, per-anchor predictive NLL values are
    supplied. PIT uses a seeded randomized empirical rank to handle ties in
    finite path ensembles; it is diagnostic, not a smoothed density estimate.
    """
    paths = np.asarray(path_log_returns, dtype=np.float64)
    truth = np.asarray(realized_log_returns, dtype=np.float64)
    if (paths.ndim != 3 or paths.shape[0] < 1 or paths.shape[1] < 2
            or paths.shape[2] < 1 or truth.shape != (paths.shape[0], paths.shape[2])):
        raise ValueError("expected [N,P>=2,T] paths and [N,T] realized returns")
    if not np.isfinite(paths).all() or not np.isfinite(truth).all():
        raise ValueError("predictive scores require finite paths and outcomes")
    if (not horizons or any(type(h) is not int or h < 1 for h in horizons)
            or tuple(sorted(set(horizons))) != horizons
            or horizons[-1] > paths.shape[2]):
        raise ValueError("horizons must be increasing and fit the supplied paths")
    if (not np.isfinite(extreme_threshold) or type(pit_seed) is not int or pit_seed < 0):
        raise ValueError("invalid calibration configuration")
    native_nll = {} if nll_by_horizon is None else dict(nll_by_horizon)
    if set(native_nll) - set(horizons):
        raise ValueError("NLL keys must be requested horizons")
    rng = np.random.default_rng(pit_seed)
    scores: list[PredictiveHorizonMetrics] = []
    for horizon in horizons:
        draws = paths[:, :, :horizon].sum(axis=-1)
        observed = truth[:, :horizon].sum(axis=-1)
        var_01, var_05, low_95, high_95 = np.quantile(
            draws, [0.01, 0.05, 0.025, 0.975], axis=1)
        lower_90, upper_90 = np.quantile(draws, [0.05, 0.95], axis=1)
        lower_95, upper_95 = low_95, high_95
        sorted_draws = np.sort(draws, axis=1)
        less = np.sum(sorted_draws < observed[:, None], axis=1)
        equal = np.sum(sorted_draws == observed[:, None], axis=1)
        pit = (less + rng.random(len(observed)) * (equal + 1)) / (draws.shape[1] + 1)
        breach_01 = observed < var_01
        breach_05 = observed < var_05
        predicted_tail_01 = np.asarray([
            row[row <= threshold].mean() for row, threshold in zip(draws, var_01, strict=True)])
        predicted_tail_05 = np.asarray([
            row[row <= threshold].mean() for row, threshold in zip(draws, var_05, strict=True)])
        extreme = observed < extreme_threshold
        fn_extreme = extreme & ~breach_05
        nll_values = native_nll.get(horizon)
        if nll_values is not None:
            nll_values = np.asarray(nll_values, dtype=np.float64)
            if nll_values.shape != observed.shape or not np.isfinite(nll_values).all():
                raise ValueError(f"native NLL for horizon {horizon} must be finite [N]")
        direction_probability = np.mean(draws > 0, axis=1)
        direction_truth = observed > 0
        direction_target = direction_truth.astype(np.float64)
        clipped_probability = np.clip(direction_probability, 1e-12, 1.0 - 1e-12)
        scores.append(PredictiveHorizonMetrics(
            horizon=horizon, samples=len(observed),
            crps=ensemble_crps(draws, observed),
            nll=None if nll_values is None else float(nll_values.mean()),
            pit_values=tuple(float(x) for x in pit),
            coverage_90=float(np.mean((observed >= lower_90) & (observed <= upper_90))),
            coverage_95=float(np.mean((observed >= lower_95) & (observed <= upper_95))),
            width_90=float(np.mean(upper_90 - lower_90)),
            width_95=float(np.mean(upper_95 - lower_95)),
            direction_brier=float(np.mean((direction_probability
                                           - direction_truth.astype(float)) ** 2)),
            direction_auc=_binary_auc(direction_probability, direction_truth),
            direction_log_loss=float(-np.mean(
                direction_target * np.log(clipped_probability)
                + (1.0 - direction_target) * np.log1p(-clipped_probability))),
            sign_accuracy=float(np.mean((direction_probability >= 0.5) == direction_truth)),
            var_01=float(np.mean(var_01)), var_05=float(np.mean(var_05)),
            var_breach_01=float(np.mean(breach_01)), var_breach_05=float(np.mean(breach_05)),
            cvar_01=float(predicted_tail_01.mean()),
            cvar_05=float(predicted_tail_05.mean()),
            realized_breach_loss_01=(float(np.mean(observed[breach_01]))
                                     if breach_01.any() else None),
            realized_breach_loss_05=(float(np.mean(observed[breach_05]))
                                     if breach_05.any() else None),
            false_negative_extreme_loss=(float(np.mean(observed[fn_extreme]))
                                         if fn_extreme.any() else 0.0),
        ))
    return tuple(scores)


def compare_path_models(
    forecasts: Mapping[str, np.ndarray],
    realized_log_returns: np.ndarray,
    *,
    anchor_timestamps_ns: np.ndarray,
    outcome_timestamps_ns: np.ndarray,
    horizons: tuple[int, ...] = (1, 5, 15, 30, 60),
    pit_seed: int = 0,
) -> dict[str, tuple[PredictiveHorizonMetrics, ...]]:
    """Score models against identical anchors and strictly future labels."""
    if not forecasts or any(not name for name in forecasts):
        raise ValueError("at least one named forecast is required")
    truth = np.asarray(realized_log_returns)
    anchors = np.asarray(anchor_timestamps_ns)
    outcomes = np.asarray(outcome_timestamps_ns)
    if (truth.ndim != 2 or anchors.shape != (truth.shape[0],)
            or outcomes.shape != truth.shape or not np.issubdtype(anchors.dtype, np.integer)
            or not np.issubdtype(outcomes.dtype, np.integer)):
        raise ValueError("timestamps must be integer ns arrays aligned to [N,T] outcomes")
    if (np.any(outcomes <= anchors[:, None]) or np.any(np.diff(outcomes, axis=1) <= 0)
            or np.any(np.diff(anchors) <= 0)):
        raise ValueError("each realized label must be strictly after its anchor and ordered")
    expected_shape = None
    for name, forecast in forecasts.items():
        paths = np.asarray(forecast)
        if expected_shape is None:
            expected_shape = paths.shape
        if (paths.ndim != 3 or paths.shape != expected_shape
                or paths.shape[0] != truth.shape[0] or paths.shape[2] != truth.shape[1]):
            raise ValueError(f"forecast {name!r} does not share common anchor/path geometry")
    return {
        name: predictive_horizon_scores(paths, truth, horizons=horizons, pit_seed=pit_seed)
        for name, paths in forecasts.items()
    }


def build_predictive_comparison_report(
    forecasts: Mapping[str, np.ndarray],
    realized_log_returns: np.ndarray,
    *,
    anchor_timestamps_ns: np.ndarray,
    outcome_timestamps_ns: np.ndarray,
    anchor_interval_ns: int,
    block_length: int,
    train_volatility: np.ndarray,
    anchor_volatility: np.ndarray,
    volatility_quantiles: tuple[float, ...] = (0.2, 0.4, 0.6, 0.8),
    metadata: Mapping[str, str],
    model_provenance: Mapping[str, Mapping[str, object]],
    horizons: tuple[int, ...] = (1, 5, 15, 30, 60),
    nll_by_model: Mapping[str, Mapping[int, np.ndarray]] | None = None,
    generated_ohlcv_by_model: Mapping[str, np.ndarray] | None = None,
    realized_ohlcv: np.ndarray | None = None,
    previous_close: np.ndarray | None = None,
    f2_bucket_ohlcv_by_model: Mapping[str, np.ndarray] | None = None,
    f2_bucket_ranges: tuple[tuple[int, int], ...] = (),
    rolling_window: int = 15,
    bootstrap_replicates: int = 2000,
    seed: int = 0,
) -> dict[str, object]:
    """Build a reproducible, stratified E0/E1/E2 forecast comparison report.

    Volatility quantile cutpoints are fitted from the caller-designated Train
    volatility series and applied to anchor-time volatility. Dataset/fold/scope
    fields are provenance labels only: this
    numerical layer cannot verify research-access authorization and marks that
    fact in the report. It does not load data or select a model.
    """
    required = {"dataset_identity", "fold_identity", "train_scope_id", "snapshot_sha256"}
    if (set(metadata) != required or any(not isinstance(value, str) or not value.strip()
                                         for value in metadata.values())):
        raise ValueError(f"metadata must contain exactly nonempty {sorted(required)}")
    anchors = np.asarray(anchor_timestamps_ns)
    train_vol = np.asarray(train_volatility, dtype=np.float64)
    anchor_vol = np.asarray(anchor_volatility, dtype=np.float64)
    truth = np.asarray(realized_log_returns)
    if (truth.ndim != 2 or train_vol.ndim != 1 or train_vol.size < 2
            or anchor_vol.shape != (truth.shape[0],)
            or not np.isfinite(train_vol).all() or not np.isfinite(anchor_vol).all()
            or np.any(train_vol < 0) or np.any(anchor_vol < 0)):
        raise ValueError("finite nonnegative Train and anchor-time volatility arrays required")
    if (not volatility_quantiles
            or any(not np.isfinite(q) or not 0 < q < 1 for q in volatility_quantiles)
            or tuple(sorted(set(volatility_quantiles))) != volatility_quantiles):
        raise ValueError("volatility quantiles must be increasing probabilities in (0,1)")
    cuts = np.quantile(train_vol, volatility_quantiles)
    if (cuts.ndim != 1 or not np.isfinite(cuts).all()
            or np.any(np.diff(cuts) <= 0)):
        raise ValueError("Train volatility cutpoints must be finite and strictly increasing")
    bins = np.searchsorted(cuts, anchor_vol, side="right").astype(np.int64)
    labels = sorted(int(value) for value in np.unique(bins))
    if len(forecasts) < 2:
        raise ValueError("comparison report requires at least two models")
    if set(model_provenance) != set(forecasts):
        raise ValueError("every forecast model must have one provenance record")
    expected_provenance_keys = {
        "model_family", "model_config_sha256", "artifact_sha256", "train_examples",
        "optimizer_updates", "training_seconds", "parameter_count", "device", "forecast_seed",
    }
    train_example_counts: set[int] = set()
    forecast_seeds: set[int] = set()
    normalized_provenance: dict[str, dict[str, object]] = {}
    for name, entry in model_provenance.items():
        if set(entry) != expected_provenance_keys:
            raise ValueError(f"model provenance for {name!r} has unexpected fields")
        for digest_key in ("model_config_sha256", "artifact_sha256"):
            digest = entry[digest_key]
            if (not isinstance(digest, str) or len(digest) != 64
                    or any(character not in "0123456789abcdef" for character in digest.lower())):
                raise ValueError(f"model provenance {digest_key} must be a SHA-256 hex digest")
        training_seconds = entry["training_seconds"]
        if (not isinstance(training_seconds, (int, float)) or isinstance(training_seconds, bool)
                or not np.isfinite(training_seconds) or training_seconds < 0):
            raise ValueError(f"model training time for {name!r} is invalid")
        if (not isinstance(entry["model_family"], str) or not entry["model_family"].strip()
                or not isinstance(entry["device"], str) or not entry["device"].strip()
                or type(entry["train_examples"]) is not int or entry["train_examples"] < 1
                or type(entry["optimizer_updates"]) is not int or entry["optimizer_updates"] < 0
                or type(entry["forecast_seed"]) is not int or entry["forecast_seed"] < 0
                or type(entry["parameter_count"]) is not int or entry["parameter_count"] < 0):
            raise ValueError(f"model provenance values for {name!r} are invalid")
        # E0 statistical baselines fit directly on the same authorized Train
        # history but do not consume supervised sequence windows. Compare the
        # E1/E2 neural candidates on identical example counts when both are in
        # the family; retain the stricter all-model rule for smaller reports.
        if not (name.upper().startswith("E0_")
                or (name == "E0" and {"E1", "E2"}.issubset(forecasts))):
            train_example_counts.add(entry["train_examples"])
        forecast_seeds.add(entry["forecast_seed"])
        normalized_provenance[name] = dict(entry)
    if len(train_example_counts) > 1 or not train_example_counts:
        raise ValueError("E1/E2 models must use the same number of authorized Train examples")
    if len(forecast_seeds) != 1:
        raise ValueError("models must share the preregistered forecast seed")
    scored = compare_path_models(
        forecasts, truth, anchor_timestamps_ns=anchors,
        outcome_timestamps_ns=outcome_timestamps_ns, horizons=horizons, pit_seed=seed)
    nlls = {} if nll_by_model is None else dict(nll_by_model)
    if set(nlls) - set(forecasts):
        raise ValueError("native NLL supplied for unknown model")
    for model_name, model_nll in nlls.items():
        scored[model_name] = predictive_horizon_scores(
            forecasts[model_name], truth, horizons=horizons,
            nll_by_horizon=model_nll, pit_seed=seed)

    generated_ohlcv = {} if generated_ohlcv_by_model is None else dict(generated_ohlcv_by_model)
    bucket_ohlcv = {} if f2_bucket_ohlcv_by_model is None else dict(f2_bucket_ohlcv_by_model)
    if set(generated_ohlcv) - set(forecasts) or set(bucket_ohlcv) - set(forecasts):
        raise ValueError("OHLCV diagnostics supplied for unknown model")
    if ((realized_ohlcv is None) != (previous_close is None)
            or bool(generated_ohlcv) != (realized_ohlcv is not None)):
        raise ValueError("generated OHLCV diagnostics require realized bars and previous closes")
    if bucket_ohlcv and (not f2_bucket_ranges or not generated_ohlcv):
        raise ValueError("F2 aggregation diagnostics require minute paths and bucket ranges")
    if bucket_ohlcv.keys() - generated_ohlcv.keys():
        raise ValueError("F2 bucket outputs require matching minute OHLCV paths")
    generation_diagnostics = {
        name: ohlcv_generation_diagnostics(
            paths, np.asarray(realized_ohlcv), previous_close=np.asarray(previous_close),
            rolling_window=rolling_window)
        for name, paths in generated_ohlcv.items()
    }
    f2_consistency = {
        name: bucket_aggregation_consistency(
            generated_ohlcv[name], buckets, bucket_ranges=f2_bucket_ranges)
        for name, buckets in bucket_ohlcv.items()
    }

    strata: dict[str, object] = {}
    for label in labels:
        selected = bins == label
        strata[str(label)] = {
            name: [asdict(score) for score in predictive_horizon_scores(
                np.asarray(paths)[selected], truth[selected], horizons=horizons,
                nll_by_horizon={
                    horizon: np.asarray(values)[selected]
                    for horizon, values in nlls.get(name, {}).items()
                }, pit_seed=seed)]
            for name, paths in forecasts.items()
        }

    pair_results: list[dict[str, object]] = []
    raw_p_values: list[float] = []
    for horizon in horizons:
        for baseline, candidate in combinations(forecasts, 2):
            result = paired_block_bootstrap_crps(
                np.asarray(forecasts[candidate]), np.asarray(forecasts[baseline]), truth,
                anchor_timestamps_ns=anchors, anchor_interval_ns=anchor_interval_ns,
                horizon=horizon, block_length=block_length,
                replicates=bootstrap_replicates,
                seed=seed + horizon + sum(map(ord, baseline + candidate)),
                baseline_name=baseline, candidate_name=candidate)
            pair_results.append(asdict(result))
            raw_p_values.append(result.p_value)
    # Holm's step-down adjustment controls family-wise error across the entire
    # preregistered model-pair x horizon family.
    ordered = sorted(range(len(pair_results)), key=lambda i: raw_p_values[i])
    adjusted = [0.0] * len(pair_results)
    running = 0.0
    for rank, index in enumerate(ordered):
        raw_p = raw_p_values[index]
        running = max(running, min(1.0, (len(ordered) - rank) * raw_p))
        adjusted[index] = running
    for index, value in enumerate(adjusted):
        pair_results[index]["holm_p_value"] = value

    report: dict[str, object] = {
        "schema": "routeb.predictive-comparison.v1",
        "metadata": dict(metadata),
        "model_provenance": normalized_provenance,
        "input_sha256": {
            "realized_log_returns": _numeric_sha256(truth, dtype="<f8"),
            "anchor_timestamps_ns": _numeric_sha256(anchors, dtype="<i8"),
            "outcome_timestamps_ns": _numeric_sha256(
                np.asarray(outcome_timestamps_ns), dtype="<i8"),
            "train_volatility": _numeric_sha256(train_vol, dtype="<f8"),
            "anchor_volatility": _numeric_sha256(anchor_vol, dtype="<f8"),
            "volatility_bin": _numeric_sha256(bins, dtype="<i8"),
            "forecasts": {name: _numeric_sha256(np.asarray(values), dtype="<f8")
                          for name, values in forecasts.items()},
            "native_nll": {name: {str(horizon): _numeric_sha256(np.asarray(values), dtype="<f8")
                                  for horizon, values in model_nll.items()}
                           for name, model_nll in nlls.items()},
            "generated_ohlcv": {name: _numeric_sha256(np.asarray(values), dtype="<f8")
                                for name, values in generated_ohlcv.items()},
            "realized_ohlcv": (None if realized_ohlcv is None
                               else _numeric_sha256(np.asarray(realized_ohlcv), dtype="<f8")),
            "previous_close": (None if previous_close is None
                               else _numeric_sha256(np.asarray(previous_close), dtype="<f8")),
            "f2_bucket_ohlcv": {name: _numeric_sha256(np.asarray(values), dtype="<f8")
                                for name, values in bucket_ohlcv.items()},
        },
        "protocol": {
            "horizons": list(horizons), "anchor_interval_ns": anchor_interval_ns,
            "block_length_anchors": block_length,
            "rolling_rv_window": rolling_window,
            "bootstrap_replicates": bootstrap_replicates, "seed": seed,
            "volatility_bins": labels, "train_volatility_quantiles": list(volatility_quantiles),
            "train_fitted_volatility_cutpoints": cuts.tolist(),
            "multiple_testing": "Holm family-wise adjustment across all model-pair x horizon tests",
        },
        "authorization_verified": False,
        "authorization_note": "Metadata are caller-supplied labels; verify registered access and fold provenance separately.",
        "overall": {name: [asdict(score) for score in scores]
                    for name, scores in scored.items()},
        "volatility_strata": strata,
        "paired_crps_differences": pair_results,
        "generation_diagnostics": generation_diagnostics,
        "f2_bucket_consistency": f2_consistency,
        "model_selection": "not_performed",
        "economic_claim": False,
    }
    canonical = json.dumps(report, sort_keys=True, separators=(",", ":"), allow_nan=False)
    report["report_sha256"] = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    return report


def paired_block_bootstrap_crps(
    candidate_paths: np.ndarray,
    baseline_paths: np.ndarray,
    realized_log_returns: np.ndarray,
    *,
    anchor_timestamps_ns: np.ndarray,
    anchor_interval_ns: int,
    horizon: int,
    block_length: int,
    replicates: int = 2000,
    seed: int = 0,
    baseline_name: str = "baseline",
    candidate_name: str = "candidate",
) -> BlockBootstrapDifference:
    """Paired moving-block CRPS bootstrap without crossing time-series gaps."""
    candidate = np.asarray(candidate_paths, dtype=np.float64)
    baseline = np.asarray(baseline_paths, dtype=np.float64)
    truth = np.asarray(realized_log_returns, dtype=np.float64)
    anchors = np.asarray(anchor_timestamps_ns)
    if (candidate.ndim != 3 or candidate.shape != baseline.shape
            or truth.shape != (candidate.shape[0], candidate.shape[2])
            or anchors.shape != (candidate.shape[0],)
            or not np.issubdtype(anchors.dtype, np.integer)
            or np.any(np.diff(anchors) <= 0)
            or not np.isfinite(candidate).all() or not np.isfinite(baseline).all()
            or not np.isfinite(truth).all()):
        raise ValueError("paired bootstrap requires aligned finite [N,P,T] arrays")
    if (type(horizon) is not int or not 1 <= horizon <= candidate.shape[2]
            or type(block_length) is not int or not 1 <= block_length <= candidate.shape[0]
            or type(anchor_interval_ns) is not int or anchor_interval_ns < 1
            or type(replicates) is not int or replicates < 100 or type(seed) is not int or seed < 0):
        raise ValueError("invalid block bootstrap configuration")
    obs = truth[:, :horizon].sum(axis=1)
    c = candidate[:, :, :horizon].sum(axis=-1)
    b = baseline[:, :, :horizon].sum(axis=-1)
    difference = _crps_per_anchor(c, obs) - _crps_per_anchor(b, obs)
    rng = np.random.default_rng(seed)
    segment_ids = np.concatenate(([0], np.cumsum(np.diff(anchors) != anchor_interval_ns)))
    valid_starts = np.asarray([
        start for start in range(len(difference) - block_length + 1)
        if segment_ids[start] == segment_ids[start + block_length - 1]
    ], dtype=np.int64)
    if not len(valid_starts):
        raise ValueError("no continuous timestamp segment is long enough for requested block")
    n_blocks = int(np.ceil(len(difference) / block_length))
    samples = np.empty(replicates, dtype=np.float64)
    for i in range(replicates):
        starts = rng.choice(valid_starts, size=n_blocks, replace=True)
        indices = np.concatenate([start + np.arange(block_length) for start in starts])[:len(difference)]
        samples[i] = difference[indices].mean()
    lo, hi = np.quantile(samples, [0.025, 0.975])
    centered = samples - samples.mean()
    observed_effect = abs(float(difference.mean()))
    p_value = (1.0 + np.count_nonzero(np.abs(centered) >= observed_effect)) / (len(samples) + 1.0)
    return BlockBootstrapDifference(
        horizon=horizon, baseline=baseline_name, candidate=candidate_name,
        mean_difference=float(difference.mean()), ci_95_low=float(lo), ci_95_high=float(hi),
        p_value=float(p_value),
        block_length=block_length, replicates=replicates)


def _ohlcv_valid_mask(bars: np.ndarray) -> np.ndarray:
    finite = np.isfinite(bars).all(axis=-1)
    prices = bars[..., :4]
    return (finite & (prices > 0).all(axis=-1) & (bars[..., 4] >= 0)
            & (bars[..., 1] >= np.maximum(bars[..., 0], bars[..., 3]))
            & (bars[..., 2] <= np.minimum(bars[..., 0], bars[..., 3])))


def _mean_lag_one_autocorrelation(rows: np.ndarray) -> float | None:
    if rows.ndim != 2 or rows.shape[1] < 3:
        return None
    values: list[float] = []
    for row in rows:
        left = row[:-1] - np.mean(row[:-1])
        right = row[1:] - np.mean(row[1:])
        denominator = float(np.sqrt(np.sum(left * left) * np.sum(right * right)))
        if denominator > 0:
            values.append(float(np.sum(left * right) / denominator))
    return float(np.mean(values)) if values else None


def _reliability_bins(probability: np.ndarray, observed: np.ndarray,
                      *, bins: int = 10) -> list[dict[str, float | int]]:
    flat_p = probability.ravel()
    flat_y = observed.astype(np.float64).ravel()
    output: list[dict[str, float | int]] = []
    assignment = np.minimum((flat_p * bins).astype(np.int64), bins - 1)
    for index in range(bins):
        selected = assignment == index
        if selected.any():
            output.append({"bin": index, "count": int(selected.sum()),
                           "mean_probability": float(flat_p[selected].mean()),
                           "observed_frequency": float(flat_y[selected].mean())})
    return output


def ohlcv_generation_diagnostics(
    generated_candles: np.ndarray,
    realized_candles: np.ndarray,
    *,
    previous_close: np.ndarray,
    rolling_window: int = 15,
    touch_thresholds: tuple[float, ...] = (0.005, 0.01),
) -> dict[str, object]:
    """Compare simulated OHLCV path properties with aligned realized bars."""
    generated = np.asarray(generated_candles, dtype=np.float64)
    realized = np.asarray(realized_candles, dtype=np.float64)
    anchor = np.asarray(previous_close, dtype=np.float64)
    if (generated.ndim != 4 or generated.shape[-1] != 5 or generated.shape[1] < 2
            or realized.shape != (generated.shape[0], generated.shape[2], 5)
            or anchor.shape != (generated.shape[0],) or not np.isfinite(anchor).all()
            or np.any(anchor <= 0)):
        raise ValueError("expected generated [N,P,T,5], realized [N,T,5], and positive anchors [N]")
    if (type(rolling_window) is not int or rolling_window < 2
            or rolling_window > generated.shape[2] or not touch_thresholds
            or any(not np.isfinite(value) or not 0 < value < 1 for value in touch_thresholds)
            or tuple(sorted(set(touch_thresholds))) != touch_thresholds):
        raise ValueError("invalid rolling window or touch thresholds")
    gen_valid = _ohlcv_valid_mask(generated)
    real_valid = _ohlcv_valid_mask(realized)
    if not real_valid.all():
        raise ValueError("realized OHLCV contains invalid bars")
    valid_paths = gen_valid.all(axis=-1)
    if not valid_paths.any():
        generated_returns = np.empty((0, generated.shape[2]), dtype=np.float64)
    else:
        selected = generated[valid_paths]
        previous = np.concatenate((np.broadcast_to(anchor[:, None, None],
                                                   (len(anchor), generated.shape[1], 1)),
                                   generated[..., :-1, 3]), axis=-1)[valid_paths]
        generated_returns = np.log(selected[..., 3] / previous)
    real_previous = np.concatenate((anchor[:, None], realized[:, :-1, 3]), axis=1)
    realized_returns = np.log(realized[..., 3] / real_previous)
    real_rolling = np.sqrt(np.mean(np.lib.stride_tricks.sliding_window_view(
        realized_returns, rolling_window, axis=1) ** 2, axis=-1))
    gen_rolling = (np.sqrt(np.mean(np.lib.stride_tricks.sliding_window_view(
        generated_returns, rolling_window, axis=1) ** 2, axis=-1))
        if len(generated_returns) else np.empty((0, generated.shape[2] - rolling_window + 1)))
    touch: dict[str, object] = {}
    valid_anchor = valid_paths.any(axis=1)
    for threshold in touch_thresholds:
        previous_gen = np.concatenate((np.broadcast_to(anchor[:, None, None],
                                                       (len(anchor), generated.shape[1], 1)),
                                       generated[..., :-1, 3]), axis=-1)
        up_hit = generated[..., 1] >= previous_gen * (1.0 + threshold)
        down_hit = generated[..., 2] <= previous_gen * (1.0 - threshold)
        valid_mask = valid_paths[:, :, None]
        counts = valid_paths.sum(axis=1)
        up_probability = np.divide(
            (up_hit & valid_mask).sum(axis=1), counts[:, None],
            out=np.full((len(anchor), generated.shape[2]), np.nan), where=counts[:, None] > 0)
        down_probability = np.divide(
            (down_hit & valid_mask).sum(axis=1), counts[:, None],
            out=np.full((len(anchor), generated.shape[2]), np.nan), where=counts[:, None] > 0)
        observed_up = realized[..., 1] >= real_previous * (1.0 + threshold)
        observed_down = realized[..., 2] <= real_previous * (1.0 - threshold)
        key = f"{threshold:.6g}"
        touch[key] = {
            "up_brier": (float(np.mean((up_probability[valid_anchor] - observed_up[valid_anchor]) ** 2))
                         if valid_anchor.any() else None),
            "down_brier": (float(np.mean((down_probability[valid_anchor] - observed_down[valid_anchor]) ** 2))
                           if valid_anchor.any() else None),
            "up_reliability": (_reliability_bins(up_probability[valid_anchor], observed_up[valid_anchor])
                               if valid_anchor.any() else []),
            "down_reliability": (_reliability_bins(down_probability[valid_anchor], observed_down[valid_anchor])
                                 if valid_anchor.any() else []),
        }
    return {
        "generated_bar_valid_rate": float(gen_valid.mean()),
        "generated_path_valid_rate": float(valid_paths.mean()),
        "realized_bar_valid_rate": float(real_valid.mean()),
        "generated_return_lag1_autocorrelation": _mean_lag_one_autocorrelation(generated_returns),
        "realized_return_lag1_autocorrelation": _mean_lag_one_autocorrelation(realized_returns),
        "generated_abs_return_lag1_autocorrelation": _mean_lag_one_autocorrelation(
            np.abs(generated_returns)) if len(generated_returns) else None,
        "realized_abs_return_lag1_autocorrelation": _mean_lag_one_autocorrelation(
            np.abs(realized_returns)),
        "generated_rolling_rv_mean": float(gen_rolling.mean()) if gen_rolling.size else None,
        "generated_rolling_rv_p95": float(np.quantile(gen_rolling, 0.95)) if gen_rolling.size else None,
        "realized_rolling_rv_mean": float(real_rolling.mean()),
        "realized_rolling_rv_p95": float(np.quantile(real_rolling, 0.95)),
        "touch_reliability": touch,
    }


def bucket_aggregation_consistency(
    minute_candles: np.ndarray,
    bucket_candles: np.ndarray,
    *,
    bucket_ranges: tuple[tuple[int, int], ...],
    rtol: float = 1e-10,
    atol: float = 1e-10,
) -> dict[str, float | int]:
    """Check F2 emitted higher-timeframe OHLCV against its synthetic minutes."""
    minutes = np.asarray(minute_candles, dtype=np.float64)
    buckets = np.asarray(bucket_candles, dtype=np.float64)
    if (minutes.ndim != 4 or minutes.shape[-1] != 5 or not bucket_ranges or buckets.ndim != 4
            or buckets.shape[:2] != minutes.shape[:2] or buckets.shape[2:] != (len(bucket_ranges), 5)
            or not np.isfinite(minutes).all() or not np.isfinite(buckets).all()
            or not np.isfinite(rtol) or not np.isfinite(atol) or rtol < 0 or atol < 0):
        raise ValueError("invalid minute/bucket OHLCV tensors or tolerances")
    previous_end = 0
    expected: list[np.ndarray] = []
    for start, end in bucket_ranges:
        if (type(start) is not int or type(end) is not int or start != previous_end
                or end <= start or end > minutes.shape[2]):
            raise ValueError("bucket ranges must be ordered, contiguous, nonempty, and in bounds")
        section = minutes[:, :, start:end]
        expected.append(np.stack((section[:, :, 0, 0], section[:, :, :, 1].max(axis=2),
                                  section[:, :, :, 2].min(axis=2), section[:, :, -1, 3],
                                  section[:, :, :, 4].sum(axis=2)), axis=-1))
        previous_end = end
    if previous_end != minutes.shape[2]:
        raise ValueError("bucket ranges must cover every generated minute")
    target = np.stack(expected, axis=2)
    equal = np.isclose(target, buckets, rtol=rtol, atol=atol)
    total = int(equal.size)
    matches = int(equal.sum())
    return {"fields_checked": total, "fields_matching": matches,
            "field_consistency_rate": float(matches / total),
            "bucket_consistency_rate": float(np.all(equal, axis=-1).mean())}


def sample_e0_paths(train_log_returns: np.ndarray, visible_log_returns: np.ndarray,
                    *, paths: int, horizon: int, seed: int,
                    ewma_decay: float = 0.94,
                    mean_block_length: int = 16) -> dict[str, np.ndarray]:
    """Generate causal multi-step S0/S1/S2 log-return paths for E0.

    `train_log_returns` is the only fitting sample. `visible_log_returns` has
    shape `[anchors, context]` and may contain only returns available at each
    forecast anchor. No realized future labels are accepted by this function.
    The returned arrays are `[anchors, paths, horizon]`.
    """
    train = np.asarray(train_log_returns, dtype=np.float64)
    visible = np.asarray(visible_log_returns, dtype=np.float64)
    if (train.ndim != 1 or train.size < 2 or visible.ndim != 2
            or visible.shape[0] < 1 or not np.isfinite(train).all()
            or not np.isfinite(visible).all()):
        raise ValueError("finite Train returns and [anchors,context] visible returns required")
    if (type(paths) is not int or paths < 2 or type(horizon) is not int or horizon < 1
            or type(seed) is not int or seed < 0 or type(mean_block_length) is not int
            or mean_block_length < 1 or not np.isfinite(ewma_decay)
            or not 0.0 < ewma_decay < 1.0):
        raise ValueError("invalid E0 path sampling configuration")

    rng = np.random.default_rng(seed)
    train_mean = float(train.mean())
    train_scale = max(float(np.sqrt(np.mean(np.square(train - train_mean)))), 1e-12)
    innovations = (train - train_mean) / train_scale
    anchors = visible.shape[0]
    zero_drift = rng.normal(0.0, train_scale, size=(anchors, paths, horizon))
    conditional_volatility = np.empty((anchors, paths, horizon), dtype=np.float64)
    bootstrap = np.empty((anchors, paths, horizon), dtype=np.float64)
    restart_probability = 1.0 / mean_block_length

    # Initialize one causal variance per anchor from Train and its visible
    # context. Generated returns update their own path variance recursively.
    train_variance = max(float(np.mean(np.square(train))), 1e-24)
    for anchor in range(anchors):
        initial_variance = train_variance
        for observed in visible[anchor]:
            initial_variance = (ewma_decay * initial_variance
                                + (1.0 - ewma_decay) * observed * observed)
        for path in range(paths):
            variance = initial_variance
            for step in range(horizon):
                sampled = float(rng.choice(innovations)) * np.sqrt(max(variance, 1e-24))
                conditional_volatility[anchor, path, step] = sampled
                variance = ewma_decay * variance + (1.0 - ewma_decay) * sampled * sampled

        for path in range(paths):
            index = int(rng.integers(train.size))
            for step in range(horizon):
                if step == 0:
                    pass
                elif rng.random() < restart_probability:
                    index = int(rng.integers(train.size))
                else:
                    index = (index + 1) % train.size
                bootstrap[anchor, path, step] = train[index]

    return {
        "S0_ZERO_DRIFT_FIXED_VOL": zero_drift,
        "S1_EWMA_VOL_TRAIN_INNOVATIONS": conditional_volatility,
        "S2_STATIONARY_BLOCK_BOOTSTRAP": bootstrap,
    }


def multi_horizon_scores(path_log_returns:np.ndarray,
                         realized_log_returns:np.ndarray, *,
                         horizons:tuple[int,...]=(1,5,15,30,60),
                         tail_threshold:float=-0.02)->tuple[HorizonMetrics,...]:
    """[anchors,paths,T] synthetic 1m log returns; [anchors,T] historical future.

    All anchor forecasts must be issued without observing realized future bars.
    The caller must enforce research-scope access rules before passing labels.
    """
    p=np.asarray(path_log_returns,dtype=np.float64)
    truth=np.asarray(realized_log_returns,dtype=np.float64)
    if p.ndim!=3 or p.shape[0]<1 or p.shape[2]<1 or truth.shape!=(p.shape[0],p.shape[2]) or p.shape[1]<2:
        raise ValueError("expected [N,P,T] simulations and [N,T] outcomes")
    if not np.isfinite(p).all() or not np.isfinite(truth).all():
        raise ValueError("nonfinite forecast")
    if (not horizons or any(type(h) is not int or h<1 for h in horizons)
        or tuple(sorted(set(horizons)))!=horizons):
        raise ValueError('horizons must be strictly increasing positive integer minutes')
    if not np.isfinite(tail_threshold):
        raise ValueError('tail threshold must be finite')
    out=[]
    for h in horizons:
        if h<1 or h>p.shape[2]:
            raise ValueError("horizon outside provided path")
        pred=p[:,:,:h].sum(-1)
        y=truth[:,:h].sum(-1)
        c80=np.quantile(pred,[.1,.9],axis=1)
        c95=np.quantile(pred,[.025,.975],axis=1)
        prob=(pred<tail_threshold).mean(1)
        hit=(y<tail_threshold).astype(float)
        out.append(HorizonMetrics(h,len(y),ensemble_crps(pred,y),
                 float(np.mean((y>=c80[0])&(y<=c80[1]))),
                 float(np.mean((y>=c95[0])&(y<=c95[1]))),
                 float(np.mean((prob-hit)**2)),tail_threshold))
    return tuple(out)


def return_paths(candles:np.ndarray, *, previous_close:np.ndarray|float)->np.ndarray:
    """Convert OHLCV paths [N,P,T,5] to *total* close-to-close log returns.

    `previous_close` is the last actually visible preforecast close, either a
    scalar or one anchor per N. It is mandatory: computing only close/open
    silently drops opening gaps and corrupts cumulative returns. Later returns
    always use each simulated previous close, including gaps.
    """
    bars=np.asarray(candles,dtype=float)
    if bars.ndim!=4 or bars.shape[-1]!=5:
        raise ValueError("expected OHLCV [N,P,T,5]")
    if (not np.isfinite(bars).all() or (bars[...,0:4]<=0).any()
        or (bars[...,4]<0).any() or bars.shape[2]<1 or bars.shape[0]<1
        or np.any(bars[...,1]<np.maximum(bars[...,0],bars[...,3]))
        or np.any(bars[...,2]>np.minimum(bars[...,0],bars[...,3]))):
        raise ValueError("finite positive path prices required")
    previous=np.concatenate([bars[...,0,0,None],bars[...,:-1,3]],axis=-1)
    anchor=np.asarray(previous_close,dtype=float)
    if anchor.ndim==0:
        anchor=np.full((bars.shape[0],),float(anchor))
    if anchor.shape!=(bars.shape[0],) or not np.isfinite(anchor).all() or (anchor<=0).any():
        raise ValueError('anchor must be finite positive scalar or [N]')
    previous[...,0]=anchor[:,None]
    return np.log(bars[...,3]/previous)
